export function getStatusLabel(status?: string | null) {
  if (!status) return 'Không có';
  return labels[status] ?? (/^[A-Z][A-Z_]+$/.test(status) ? 'Chưa xác định' : status);
}

export function getPaymentMethodLabel(method?: string | null) {
  switch (method) {
    case 'SEPAY': return 'Chuyển khoản ngân hàng';
    case 'SANDBOX': return 'Thanh toán qua QR';
    default: return getStatusLabel(method);
  }
}

export function getDeliveryMethodLabel(method: string) {
  return ({ PICKUP: 'Nhận trực tiếp', DELIVERY: 'Giao hàng', BOTH: 'Nhận trực tiếp hoặc giao hàng' } as Record<string, string>)[method] ?? 'Chưa xác định';
}
